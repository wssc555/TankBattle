    @Test
    void legacyBitForBitEquivalence() {
        for (int[] g : GOLDEN) {
            BrickWall wall = new BrickWall(WALL_X, WALL_Y, g[0]);
            int before = wall.shapeBits();
            boolean stopped = wall.damage(new Rectangle(g[3], g[4], g[5], g[6]),
                    Direction.fromCode(g[1]), g[2]);

            int nullMask = 0;
            Rectangle[] quadrants = wall.quadrants();
            for (int q = 0; q < 4; q++) {
                if (quadrants[q] == null) {
                    nullMask |= 1 << q;
                }
            }
            String where = "init=0x" + Integer.toHexString(g[0]) + " dir=" + g[1] + " power=" + g[2]
                    + " rect=[" + g[3] + "," + g[4] + " " + g[5] + "x" + g[6] + "]";
            assertEquals(g[7], wall.shapeBits(), "shapeBits 不一致: " + where);
            assertEquals(g[8], nullMask, "象限 null 模式不一致: " + where);
            assertEquals(before != wall.shapeBits(), stopped,
                    "位图变化与拦截判定应等价（守卫滑弹 = 不置位不拦截）: " + where);
            assertTrue((wall.shapeBits() & ~0xFFFF) == 0);
            assertEquals(0, before & ~wall.shapeBits(), "位图只能置位: " + where);
        }
    }
